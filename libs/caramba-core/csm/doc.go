// Package csm реализует верификатор CSM/1 (Caramba Signed Manifest).
//
// Нормативные документы:
//
//	apps/caramba-client/docs/protocol/03-WIRE.md   формат кадра, профили CBOR и Ed25519, реестр кодов ошибок
//	apps/caramba-client/docs/protocol/02-SPEC.md   модель документов, таблица авторизации, свежесть
//	apps/caramba-client/docs/protocol/01-DECISION.md раздел 6, 22 инварианта
//
// Общий корпус тестовых векторов лежит в
// apps/caramba-client/docs/protocol/05-TEST-VECTORS и является merge gate:
// пакет обязан согласовываться с ним по вердикту И по коду причины.
//
// Три правила, которые задают форму этого пакета:
//
//  1. Проверка идёт по принятым байтам. Ни один путь не пересериализует,
//     не переупорядочивает и не нормализует полезную нагрузку перед проверкой
//     подписи, и нигде нет сравнения "перекодировать и сравнить"
//     (03-WIRE.md 1.3, инвариант 1).
//  2. Длина кадра точная. Хвостовые байты, завышенный nsigs и короткий кадр
//     это отказ, а не допустимый вход (03-WIRE.md 1.1, инвариант 2).
//  3. Роль и порог читаются из РАНЕЕ доверенного документа, никогда из
//     проверяемого. Единственное исключение это ротация корня, которой нужны
//     оба набора (03-WIRE.md 7.1 и 7.3, инвариант 4). Ни одна функция пакета
//     не возвращает открытый ключ без его роли.
//
// Разбор и проверка это разные исходы с разными кодами: ошибки семейства
// E_PARSE_* решаются целиком по входным байтам, без ключевого материала и без
// сохранённого состояния; ошибки E_VERIFY_* и E_SEAL_* требуют доверенного
// документа, закреплённого pid, отметки версии, часов или выданного nonce.
// Вызывающий различает их через Error.IsParse и Error.IsVerify.
