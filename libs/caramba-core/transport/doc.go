// Package transport реализует лестницу транспортов CSM/1 и путь выборки
// подписанных документов.
//
// Нормативные документы:
//
//	apps/caramba-client/docs/protocol/02-SPEC.md   раздел 8, лестница; раздел 5, свежесть; раздел 9, регистрация
//	apps/caramba-client/docs/protocol/03-WIRE.md   раздел 11, бюджет размеров; раздел 13, эндпойнты; раздел 14, URL
//	apps/caramba-client/docs/protocol/01-DECISION.md раздел 6, инварианты 5, 8, 12, 16, 17
//
// Четыре правила, которые задают форму этого пакета.
//
//  1. Ступень, выключенная пользователем, НЕ пробуется никогда: ни при отказе
//     всех остальных, ни на холодном старте, ни по команде оператора. Это
//     абсолютное правило 02-SPEC.md 8, и в коде оно живёт ровно в одном месте,
//     в Ladder.effectiveOrder.
//  2. Ступень, для которой в этом репозитории нет компонента (onion), всё равно
//     скомпилирована и видна в State со своей причиной. Скрытая ступень это
//     ступень, которую пользователь не может проверить, а инвариант 17 требует
//     обратного.
//  3. Бюджет соединения считается ДО отправки запроса и по максимально
//     возможному ответу (thr.resp_max), а не по фактическому. Инвариант 5.
//  4. Истёкший документ по-прежнему подключает. Он отвергается только для
//     принятия новых настроек и нового статуса. Инвариант 16, абсолютный.
//
// Разбор и проверка кадров живут в пакете csm и здесь не дублируются: этот
// пакет только приносит байты и решает, что с ними делать дальше.
