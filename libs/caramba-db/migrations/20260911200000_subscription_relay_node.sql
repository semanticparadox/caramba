-- Закрепление КОНКРЕТНОГО relay-узла за подпиской (в дополнение к стране).
--
-- relay_country отвечает на вопрос «через какую страну входить», и пока в
-- стране один релей, этого хватало. С двумя и более релеями в одной стране
-- пользователю нужно уметь выбрать конкретный (город, имя), а генератору —
-- строить цепочки только через него. NULL означает «страны достаточно»:
-- в конфиг попадают все релеи страны, как и раньше.
--
-- ON DELETE SET NULL: удалённый в панели релей не должен оставлять подписку
-- с висячим закреплением — выбор молча возвращается к уровню страны.
ALTER TABLE subscriptions
    ADD COLUMN IF NOT EXISTS relay_node_id BIGINT REFERENCES nodes(id) ON DELETE SET NULL;
