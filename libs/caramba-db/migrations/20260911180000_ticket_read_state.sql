-- Состояние «прочитано» у тикета поддержки (раунд 6, зона C).
--
-- Зачем. До этой миграции «непрочитанные ответы» считались как сообщения
-- поддержки после ПОСЛЕДНЕГО сообщения самого пользователя. Простое прочтение
-- ответа маркер не снимало: бейдж «новое» горел, пока человек сам что-то не
-- напишет, и уведомление о новом ответе нельзя было честно погасить.
--
-- Теперь у тикета есть момент, когда владелец последний раз открывал
-- переписку (tickets_service::get_ticket для не-админа ставит NOW()).
-- Непрочитанное = ответы поддержки/системы новее и этого момента, и
-- последнего сообщения пользователя (собственный ответ по-прежнему означает,
-- что всё до него прочитано).
--
-- Миграция аддитивная: одна колонка, NULL для старых строк = «ещё не открывал
-- после релиза», тогда работает прежний расчёт по последнему сообщению.

ALTER TABLE tickets ADD COLUMN IF NOT EXISTS user_last_read_at TIMESTAMPTZ;

COMMENT ON COLUMN tickets.user_last_read_at IS
    'Когда владелец последний раз открывал переписку (NULL = ещё не открывал после релиза read-state)';
