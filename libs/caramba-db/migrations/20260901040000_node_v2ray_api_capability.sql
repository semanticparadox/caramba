-- Умеет ли sing-box на узле отдавать статистику по пользователям.
--
-- Предохранитель для выката, а не справочная информация. Панель пишет узлу
-- секцию `experimental.v2ray_api` только когда здесь TRUE: официальная сборка
-- SagerNet идёт без тега `with_v2ray_api` и отвергает такую секцию при старте
-- («v2ray api is not included in this build»), то есть узел не поднимается
-- вовсе. Без флага выкат панели раньше узлов положил бы VPN сразу всем.
--
-- Значение по умолчанию FALSE, а не NULL: неизвестность здесь должна читаться
-- как «не умеет». Агент выставляет флаг в первом же heartbeat после
-- обновления, поэтому раскатка получается пошаговой сама собой — узел
-- начинает получать секцию ровно тогда, когда научился её понимать.
ALTER TABLE nodes
    ADD COLUMN IF NOT EXISTS supports_v2ray_api BOOLEAN NOT NULL DEFAULT FALSE;
