/// Разбор аргументов запуска десктопного процесса.
///
/// ЗАЧЕМ. До этого приложение не отличало «человек открыл меня сам» от «меня
/// поднял автозапуск при входе в систему», и настройка «запуск без окна»
/// действовала на ОБА случая: включив её ради тихого старта при входе, человек
/// терял окно и при двойном клике по ярлыку. Регистрация автозапуска на Windows
/// и Linux умеет передавать аргументы, поэтому там мы подписываем запуск флагом
/// [kAutostartFlag] и решаем показ окна по нему. macOS (`SMAppService`) argv не
/// передаёт: там факт автозапуска неизвестен, и решение остаётся прежним.
library;

/// Флаг, которым регистрация автозапуска подписывает запуск при входе.
///
/// Один литерал на три места: аргумент `launch_at_startup` (реестр/`.desktop`),
/// задача планировщика Windows из инсталлятора и разбор здесь. Разъехавшись,
/// флаг перестал бы узнаваться молча.
const String kAutostartFlag = '--autostart';

/// Что процесс узнал о себе из командной строки.
class LaunchArgs {
  /// Запуск пришёл от автозапуска при входе в систему.
  final bool autostart;

  const LaunchArgs({this.autostart = false});

  /// Разбирает `main(List<String> args)`.
  ///
  /// Остальные аргументы (диплинк `caramba://…` на Windows приходит тем же
  /// argv) не наши: их читает `app_links`, здесь они просто пропускаются.
  factory LaunchArgs.parse(List<String> args) =>
      LaunchArgs(autostart: args.any((a) => a.trim() == kAutostartFlag));
}

/// Показывать ли окно на старте.
///
/// [launchedByAutostart] `null` означает «платформа не сообщает причину
/// запуска» (macOS): тогда «запуск без окна» действует при каждом запуске, как
/// и раньше, и подсказка в настройках об этом говорит. Там, где причина
/// известна, окно прячется ТОЛЬКО при автозапуске: ручной запуск обязан
/// показать окно всегда, иначе двойной клик по ярлыку выглядит как «ничего не
/// произошло».
bool shouldShowWindowOnLaunch({
  required bool startInTray,
  required bool? launchedByAutostart,
}) {
  if (!startInTray) return true;
  if (launchedByAutostart == null) return false;
  return !launchedByAutostart;
}
