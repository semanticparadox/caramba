/// Режим раздельного туннелирования — ОДИН на списки сайтов и приложений.
///
/// Файл называется split_app.dart по историческим причинам: здесь жил ещё и
/// класс `SplitApp` со списком «установленных приложений». Тот список был
/// демонстрационным на ВСЕХ платформах (перечислять приложения было нечем),
/// его идентификаторы не совпадали ни с одним реальным процессом, и каждый его
/// тумблер был переключателем, который ничего не переключает. Он удалён, а не
/// спрятан за флагом: мёртвая фикция в сборке рано или поздно снова окажется на
/// экране.
///
/// Теперь источник настоящий: на Android приложения перечисляет
/// `CarambaVpn.listInstalledApps` (канал `com.caramba/vpn`) и применяет
/// `VpnService.Builder`, на десктопе имя процесса выбирают файловым диалогом, а
/// правила ядра совпадают по `PROCESS-NAME`. Модель установленного приложения
/// живёт в плагине (`package:caramba_vpn`, `InstalledApp`), потому что её форма
/// это контракт канала, а не форма экрана; здесь остаётся только режим.
library;

/// Режим раздельного туннелирования (caramba-core `Policy.Split`):
/// off = списков нет; onlySelected = через VPN только перечисленное
/// (`AllowDomains`/`AllowSites`/`AllowProcesses`); bypassSelected =
/// перечисленное мимо VPN (`BypassDomains`/`BypassProcesses`).
///
/// РЕЖИМ ОБЩИЙ для «Правил по сайтам» и «Правил по приложениям», и делить его
/// надвое нельзя: в ядре `Policy.Split.Mode` ровно один, и он относится сразу к
/// доменам и к процессам. Два переключателя в UI поверх одного поля означали бы,
/// что второй молча переставляет первый. Поэтому у каждого списка свой экран, но
/// подписи режима на них разные — [SplitModeX] говорит про сайты, [SplitModeAppsX]
/// про приложения.
enum SplitMode { off, onlySelected, bypassSelected }

extension SplitModeX on SplitMode {
  String get title => switch (this) {
    SplitMode.off => 'Выключено',
    SplitMode.onlySelected => 'Только выбранные сайты',
    SplitMode.bypassSelected => 'Кроме выбранных сайтов',
  };

  String get desc => switch (this) {
    SplitMode.off => 'Действует общий режим, списков нет.',
    SplitMode.onlySelected =>
      'Через VPN идут только сайты из списка, всё остальное — напрямую. '
          'Режим при этом не применяется.',
    SplitMode.bypassSelected =>
      'Сайты из списка всегда идут напрямую, всё остальное — по режиму.',
  };
}

/// Тот же режим словами экрана «Правила по приложениям».
///
/// Отдельное расширение, а не второй enum: величина одна, и завести ей второе
/// имя значило бы завести второе состояние. Отличаются только подписи — на
/// экране сайтов человек выбирает судьбу САЙТОВ, здесь — приложений.
extension SplitModeAppsX on SplitMode {
  String get appsTitle => switch (this) {
    SplitMode.off => 'Выключено',
    SplitMode.bypassSelected => 'Все через VPN, кроме списка',
    SplitMode.onlySelected => 'Только список через VPN',
  };

  String get appsDesc => switch (this) {
    SplitMode.off => 'Списков нет: весь трафик идёт по общему режиму.',
    SplitMode.bypassSelected =>
      'Приложения из списка всегда идут напрямую, мимо туннеля. '
          'Остальные идут по общему режиму.',
    SplitMode.onlySelected =>
      'Через VPN идут только приложения из списка, остальные напрямую.',
  };
}
